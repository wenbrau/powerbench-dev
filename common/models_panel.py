def _as_tuple(v):
    if v is None:
        return None
    return (v,) if isinstance(v, str) else tuple(v)


def select(origin=None, stratum=None, status=None, lab=None):
    """Model ids matching every filter given. Each filter takes a string or a list of strings;
    omitted filters do not constrain. `status` defaults to everything EXCEPT excluded, because a
    caller that wants excluded models has to say so."""
    origin, stratum, lab = _as_tuple(origin), _as_tuple(stratum), _as_tuple(lab)
    status = _as_tuple(status)
    out = []
    for mid, m in MODELS.items():
        if status is None:
            if m["status"] == "excluded":
                continue
        elif m["status"] not in status:
            continue
        if origin and m["origin"] not in origin:
            continue
        if stratum and m["stratum"] not in stratum:
            continue
        if lab and m["lab"] not in lab:
            continue
        out.append(mid)
    return out


def runner_arm(model_or_stratum: str) -> str:
    """The `--reasoning` value for a model id or a stratum name."""
    s = MODELS[model_or_stratum]["stratum"] if model_or_stratum in MODELS else model_or_stratum
    return RUNNER_ARM[s]


def cannot_disable() -> dict:
    """model id -> minimum reasoning payload, for models that CANNOT run with reasoning off.

    This is the table the runners hold as CANNOT_DISABLE. Membership is a property of the model
    (stratum "reasoning"), not of the `floor` field: a model that merely HAS a minimum effort we
    sometimes want is not a model that is unable to serve the off arm, and conflating the two
    would make the runners skip it whenever --reasoning off is requested.
    """
    return {mid: m["floor"] for mid, m in MODELS.items()
            if m["stratum"] == REASONING and m.get("floor")}


def min_effort() -> dict:
    """model id -> the smallest reasoning payload the endpoint accepts, for ANY model that has one.

    Used by the runners' --min-effort flag to run the ON arm at the floor instead of at whatever
    the provider defaults to -- which matters because the defaults are not modest: glm-5.3
    defaults to effort `max`. Includes models that could also run with reasoning off (kimi-k3),
    which is exactly the case `cannot_disable()` must not cover.
    """
    return {mid: m["floor"] for mid, m in MODELS.items() if m.get("floor")}


def stratum(target: str) -> str:
    """The model's declared stratum, or "" for a model this file does not know."""
    m = MODELS.get(target)
    return m["stratum"] if m else ""


def status(target: str) -> str:
    """The model's declared status ("run" | "pending" | "excluded"), or "" if it is not listed."""
    m = MODELS.get(target)
    return m["status"] if m else ""


def reasoning_forced(target: str) -> bool:
    """Is a reasoning-enabled arm on this model a CONSTRAINT rather than a choice?

    True  = stratum "reasoning": the endpoint will not disable thinking, so running it ON is the
            only condition available. These are stratum B.
    False = stratum "no_reasoning": the model can run with reasoning verified off, so an ON row is
            a VOLUNTARY-ON reference, deliberately bought (configuration 3 in common/run_scope.py).

    The runners stamp this on every row. It exists because `reasoning_arm` reads "on" for both
    cases, and the analysis layer must be able to tell a forced-ON row from a voluntarily-ON one
    without re-deriving it from this file -- which would silently change the meaning of rows
    already written the day a model moves stratum. It is deliberately NOT a list of approved
    reference models: that list is not settled (candidates: deepseek-v4-pro-0813, kimi-k3), and
    this field does not need it to be.
    """
    return stratum(target) == REASONING


def batch_approved() -> dict:
    """model id -> True, for the models APPROVED for the batch transport.

    Half the gate. `2_run_targets/batch_client.check_batch_endpoint()` is the other half and runs
    live before every batch run: exactly one endpoint, the same endpoint tag as the sync pin,
    strictly cheaper. A model must pass both -- a decision of ours AND a fact about the market.
    """
    return {mid: True for mid, m in MODELS.items() if m.get("batch")}


