def runs_with(model: str, bank: str | None = None) -> list[dict]:
    """Runs already on disk that list `model` as a target, newest first.

    Reads the `.meta.json` sidecars in current/runs/ only -- cheap, and exact about what was
    REQUESTED. A model rejected at preflight would still appear here, which is the right bias for
    a warning. Pass `bank` (a path or a bare filename) to ask only about that bank.
    """
    want_bank = os.path.basename(bank) if bank else None
    hits = []
    for meta_path in glob.glob(os.path.join(RUNS_DIR, "*.meta.json")):
        try:
            with open(meta_path, encoding="utf-8") as f:
                meta = json.load(f)
        except (OSError, ValueError):
            continue
        if model not in (meta.get("targets") or []):
            continue
        meta_bank = os.path.basename((meta.get("bank") or "").replace("\\", "/"))
        if want_bank and meta_bank != want_bank:
            continue
        hits.append({"run": os.path.basename(meta_path).replace(".meta.json", ""),
                     "bank": meta_bank, "arm": meta.get("reasoning_arm"),
                     "mtime": os.path.getmtime(meta_path)})
    return sorted(hits, key=lambda h: h["mtime"], reverse=True)


def check_only_flag(model: str, bank: str | None, run_anyway: bool) -> None:
    """Guard behind `--only`: refuse a model that has already been run, unless --runanyway.

    Two independent signals, either of which trips it: the declared status in this file, and the
    runs actually on disk. Disagreement between them is itself worth seeing, so both are printed.
    """
    if model not in MODELS:
        print(f"!! {model} is not in common/models_panel.py. Add it there so the panel, the "
              f"US/CN balance and the analysis layer all know about it.")
        return
    declared = MODELS[model]["status"]
    if declared == "excluded":
        raise SystemExit(f"{model} is marked excluded in common/models_panel.py: "
                         f"{MODELS[model].get('why', '')}")
    hits = runs_with(model, bank)
    if declared != "run" and not hits:
        return                                        # never run: just go
    print(f"\n!! {model} looks ALREADY RUN.")
    print(f"   status in common/models_panel.py: {declared!r}")
    if hits:
        where = f" on {os.path.basename(bank)}" if bank else ""
        print(f"   runs on disk that list it as a target{where}:")
        for h in hits[:6]:
            print(f"     - {h['run']}  (bank {h['bank']}, arm {h['arm']})")
    else:
        print("   no run on disk lists it, though: the status may be stale, or the run predates "
              "the meta convention.")
    if not run_anyway:
        raise SystemExit("   refusing to spend on it again. Pass --runanyway to run it regardless "
                         "(a re-run belongs in a NEW --out, never a resume of the old file).")
    print("   --runanyway passed: running it again.\n")


def confirm_plan(rows, datasets, assume_yes=False, warning=None) -> None:
    """Print the plan and ask for confirmation before anything is spent.

    `rows` is a list of (model id, reasoning label, provider label); `datasets` a list of strings
    describing what will be run over; `warning` an optional block printed immediately before the
    question, for a commitment the plan itself does not convey. Non-interactive callers must pass
    --yes explicitly: a run that cannot ask is not allowed to assume.
    """
    print("\n" + "=" * 78)
    print("You'll run the following models:")
    print(f"  {'model':34s} {'reasoning':11s} provider")
    for mid, reasoning, provider in rows:
        print(f"  {mid:34s} {reasoning:11s} {provider}")
    print("\non the following datasets:")
    for d in datasets:
        print(f"  {d}")
    print("=" * 78)
    # A warning that belongs to the QUESTION, not to the plan: printed last, immediately above
    # `Continue?`, because the batch transport changes what answering yes commits you to. A
    # synchronous run can be stopped with Ctrl+C and everything already paid for is on disk; a
    # batch commits its whole spend at submit and cannot be interrupted. That difference is the
    # single thing a person approving a batch plan most needs to have read.
    if warning:
        for _line in str(warning).splitlines():
            print(_line)
        print("=" * 78)
    if assume_yes:
        print("--yes: continuing without asking.\n")
        return
    no_tty = "Continue? -- nobody can answer on this stdin. Nothing was spent. Re-run with --yes " \
             "if the plan above is already approved."
    # isatty() is not the reliable signal it looks like: some wrappers (agent shells, CI runners)
    # report a tty and then hand input() an immediate EOF. Both paths therefore end the same way,
    # and the default on an unanswered prompt is NO.
    if not sys.stdin.isatty():
        raise SystemExit(no_tty)
    try:
        answer = input("Continue? [y/N] ").strip().lower()
    except EOFError:
        raise SystemExit(no_tty)
    if answer not in ("y", "yes"):
        raise SystemExit("aborted; nothing was spent.")
    print()


# ------------------------------------------------------------------------------------- CLI
def _cli():
    args = sys.argv[1:]

    def opt(name):
        return args[args.index(name) + 1] if name in args else None

    if "--check" in args:
        print(f"{'model':34s} {'declared':10s} runs on disk")
        bad = 0
        for mid, m in MODELS.items():
            hits = runs_with(mid)
            note = ", ".join(h["run"] for h in hits[:3]) or "-"
            flag = ""
            if m["status"] == "run" and not hits:
                flag, bad = "  <<< declared run, nothing on disk", bad + 1
            if m["status"] == "pending" and hits:
                flag, bad = "  <<< declared pending, but ran", bad + 1
            print(f"{mid:34s} {m['status']:10s} {note}{flag}")
        print(f"\n{bad} disagreement(s) between this file and current/runs/.")
        return

    picked = select(origin=opt("--origin"), stratum=opt("--stratum"),
                    status=opt("--status") or ("run", "pending", "excluded"),
                    lab=opt("--lab"))
    if "--csv" in args:
        # One line, comma-separated: the shape the runners' TARGETS env var takes. It exists
        # because the obvious pipeline -- print one id per line, then join -- is a different
        # incantation in every shell, and in cmd.exe it needs a `for /f` loop with delayed
        # expansion. One flag removes that from the instructions on all four platforms.
        print(",".join(picked))
        return
    if any(a.startswith("--") for a in args):
        for mid in picked:
            print(mid)
        return
    print(f"{'model':34s} {'short':22s} {'orig':5s} {'stratum':13s} {'status':9s} "
          f"{'provider':14s} {'AA':>3s}")
    for mid in picked:
        m = MODELS[mid]
        print(f"{mid:34s} {m['short']:22s} {m['origin']:5s} {m['stratum']:13s} "
              f"{m['status']:9s} {str(m['provider']):14s} "
              f"{'' if m['aa_index'] is None else m['aa_index']:>3}")
    n_run = len(select(status='run'))
    print(f"\n{len(picked)} models listed | {n_run} already run | "
          f"US {len(select(origin='US'))} / CN {len(select(origin='CN'))} / "
          f"KR {len(select(origin='KR'))}  (excluded models not counted)")


if __name__ == "__main__":
    _cli()
